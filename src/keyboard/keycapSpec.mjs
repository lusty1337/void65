// размеры колпачка, общие для генератора геометрии и для стека слоёв.
// в .mjs по той же причине, что и раскладка: файл читает офлайн-генератор
// в node, а .ts он импортировать не умеет. иначе высота посадки подбирается
// на глаз и расходится с глубиной полости, а шток вылезает сквозь крышку

/** высота самого высокого ряда колпачков в мировых единицах */
export const CAP_HEIGHT = 0.42;

// глубина шахты под шток, от подошвы вверх. колпачок садится по самую её
// крышку, и от глубины зависит, насколько низко он сядет: на мелкой юбка
// не доставала до корпуса свитча, и сбоку был виден крест штока
export const SOCKET_DEPTH = 0.22;

// полуразмеры гнезда под шток: вылет лучей креста и полуширина планки.
// крест - единственная деталь, по которой изнанку MX-колпачка узнают
// с одного взгляда. числа взяты от самого штока плюс пять сотых миллиметра
// зазора, ровно чтобы колпачок надевался, а не втирался: на прежних, втрое
// щедрее, в проёме было видно, что клавиша болталась бы
export const SOCKET_A = 0.1126;
export const SOCKET_B = 0.1126;
export const SOCKET_BAR = 0.0404;

/**
 * зазор между верхом корпуса свитча и подошвой колпачка в непрожатом
 * состоянии: без него колпачок лежит на корпусе и ход пропадает
 */
export const CAP_CLEARANCE = 0.006;
