// один экземпляр тяжёлой заготовки на всю страницу. дороже всего листы
// с вырезами: у пластины и пены по восемь десятков отверстий, и триангуляция
// такого контура в ExtrudeGeometry занимает секунды сплошной блокировки.
//
// потребителей у каждой заготовки больше одного, хотя сцена теперь одна:
// слой колпачков и сорвавшийся колпачок берут общий атлас, каркас на входе
// клонирует ту же геометрию, а StrictMode в разработке монтирует дерево
// дважды.
//
// МАТЕРИАЛЫ сюда класть нельзя: волна проявления правит их шейдер на лету,
// и у каждого потребителя свои униформы - общий раздал бы всем чужой ход.
//
// ценой этого заготовки живут до конца страницы: dispose по размонтированию
// слоя им не годится, их держит кто-то ещё
const store = new Map<string, unknown>();

export function shared<T>(key: string, build: () => T): T {
  if (!store.has(key)) store.set(key, build());
  return store.get(key) as T;
}
