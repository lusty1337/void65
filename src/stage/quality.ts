// уровень качества считается один раз при загрузке и дальше не меняется:
// смена dpr или карты теней на живой сцене пересоздаёт буферы рендерера
// и заставляет три пересобрать программы - те самые секунды блокировки,
// под которые выстроен вход с заставкой.
//
// решаем НЕ по ширине окна: она говорит о вёрстке, а не о железе - узкое
// окно на рабочей машине обычное дело, а планшет набок шире иного ноутбука
export type Tier = 'high' | 'low';

function detect(): Tier {
  if (typeof window === 'undefined') return 'high';
  // ?q=low / ?q=high - не отладочный хвост, а единственный способ снять
  // мобильный уровень headless-браузером: он рапортует мышь и восемь ядер,
  // сколько окно ни сужай
  const forced = new URLSearchParams(window.location.search).get('q');
  if (forced === 'low' || forced === 'high') return forced;

  const coarse = window.matchMedia?.('(pointer: coarse)').matches ?? false;
  const weak = (navigator.hardwareConcurrency ?? 8) <= 4;
  return coarse || weak ? 'low' : 'high';
}

export const TIER: Tier = detect();
export const LOW = TIER === 'low';

// потолок плотности пикселей общий на оба уровня. у телефона плотность
// бывает 3, так что двойка и так срезает больше половины заливки, а ниже
// нельзя: клавиатура на общем плане набрана из тонких рёбер, и на полутора
// они рассыпаются лесенкой
export const MAX_DPR: [number, number] = [1, 2];

/** сторона карты теней */
export const SHADOW_SIZE = LOW ? 1024 : 2048;

/** сторона карты окружения: из неё берётся почти вся освещённость */
export const ENV_RES = LOW ? 256 : 512;

// на мобильном вдвое меньше, но НЕ ноль. один SMAA не справился: он
// разбирает края по готовой картинке и хорошо ведёт длинную ровную
// границу, а тут полсотни коротких рёбер колпачков - вместо лесенки
// остаётся мыло
export const MSAA = LOW ? 2 : 4;

// каркас на входе снимается: это лишний клон половины модели и ещё один
// проход по её геометрии ровно тогда, когда телефон занят сборкой шейдеров
export const WIREFRAME_INTRO = !LOW;

// 'soft' - это PCF с широким ядром: каждый затенённый фрагмент берёт
// с карты пучок выборок вместо одной. дорожает именно заливка, которой
// на телефоне и так вдвое больше от плотности. у 'percentage' край тени
// жёстче, и на экране в ладонь этого не видно
export const SHADOW_KIND: 'soft' | 'percentage' = LOW ? 'percentage' : 'soft';

// площадной источник в three считается интегралом по четырёхугольнику
// с двумя выборками из таблиц - на порядок дороже направленного, и платит
// за это каждый фрагмент. второй стоит на 0.14 и держит нижнюю кромку
// корпуса: на телефоне за него отдают полный проход заливки
export const FILL_LIGHTS = LOW ? 1 : 2;

// через сколько кадров перерисовывается карта теней. тень мягкая, отставания
// на кадр глазом не поймать, а стоит проход целых семьдесят тысяч
// треугольников - столько же, сколько основной
export const SHADOW_EVERY = LOW ? 2 : 1;
