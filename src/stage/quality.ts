// уровень качества считается один раз при загрузке и дальше не меняется:
// смена карты теней или набора материалов на живой сцене заставляет три
// пересобрать программы - те самые секунды блокировки, под которые выстроен
// вход с заставкой. на ходу меняется только плотность пикселей
// (resolution.tsx): от неё пересоздаются буферы, а шейдеры остаются.
//
// решаем НЕ по ширине окна: она говорит о вёрстке, а не о железе - узкое
// окно на рабочей машине обычное дело, а планшет набок шире иного ноутбука
export type Tier = 'high' | 'low';

function detect(): Tier {
  if (typeof window === 'undefined') return 'high';
  // ?q=low / ?q=high - не отладочный хвост, а единственный способ снять
  // мобильный уровень headless-браузером: он рапортует мышь и восемь ядер,
  // сколько окно ни сужай
  const forced = new URLSearchParams(window.location.search).get('q');
  if (forced === 'low' || forced === 'high') return forced;

  const coarse = window.matchMedia?.('(pointer: coarse)').matches ?? false;
  const weak = (navigator.hardwareConcurrency ?? 8) <= 4;
  return coarse || weak ? 'low' : 'high';
}

export const TIER: Tier = detect();
export const LOW = TIER === 'low';

// потолок плотности пикселей общий на оба уровня. у телефона плотность
// бывает 3, так что двойка и так срезает больше половины заливки. ниже
// сцена спускается только сама, когда железо не держит кадр: на полутора
// тонкие рёбра клавиатуры на общем плане рассыпаются лесенкой, и платить
// этим стоит только за плавность
export const MAX_DPR = 2;

// ниже этой плотности сцена не спускается. на телефоне пол выше: там
// плотность экрана 2-3, и картинка, посчитанная в единице, растягивается
// втрое - это уже не мягкость, а видимые пиксели на кромках корпуса.
// полтора от двух - это меньше половины заливки, и за скорость платится
// именно ими, а не резкостью
export const DPR_FLOOR = LOW ? 1.5 : 1;

// ступени спуска. каждая срезает от четверти до трети пикселей: мельче
// шаг не успевает за просадкой, крупнее - картинка заметно прыгает
export const DPR_STEPS = [2, 1.75, 1.5, 1.25, 1].filter((step) => step >= DPR_FLOOR);

/** сторона карты теней */
export const SHADOW_SIZE = LOW ? 1024 : 2048;

/** сторона карты окружения: из неё берётся почти вся освещённость */
export const ENV_RES = LOW ? 256 : 512;

// одинаково на обоих уровнях, и на телефоне это важнее, чем на десктопе:
// многовыборочный буфер считает освещение РАЗ на пиксель и умножает только
// покрытие краёв, поэтому на плиточной видеокарте он разрешается прямо
// в её памяти и стоит куда дешевле лишней плотности. четыре выборки
// при плотности полтора выглядят лучше, чем две при двух, и обходятся
// дешевле. на замере разница между двумя и четырьмя - десятая доля
// миллисекунды.
//
// один SMAA вместо него не справился: он разбирает края по готовой
// картинке и хорошо ведёт длинную ровную границу, а тут полсотни коротких
// рёбер колпачков - вместо лесенки остаётся мыло
export const MSAA = 4;

// SMAA идёт отдельным полноэкранным проходом и тянет за собой копию буфера
// глубины. на плиточной видеокарте телефона каждый такой проход - это
// выгрузка и загрузка всего кадра, а при плотности 2 и MSAA лесенки на
// экране в ладонь уже не разглядеть. на замере без него кадр легче
// на восьмую часть. на десктопе остаётся: снимает дрожание тонких кромок
// корпуса на движении
export const SMAA_PASS = !LOW;

// настоящее преломление - это вся сцена, нарисованная второй раз в отдельный
// буфер с четырёхкратным MSAA и цепочкой мипов, ради стенок колпака
// в миллиметр толщиной. на замере это треть кадра и сорок процентов
// треугольников. на телефоне стекло подделано смешиванием: сквозь такую
// стенку преломления не видно, а блик остаётся тот же
export const REAL_GLASS = !LOW;

// пружина внутри свитча - сорок три тысячи треугольников на клавиатуру,
// седьмая часть всей сцены. на экране телефона свитч в разборке меньше
// ногтя, и спираль за прозрачным колпаком там не различить
export const SWITCH_SPRINGS = !LOW;

// каркас на входе снимается: это лишний клон половины модели и ещё один
// проход по её геометрии ровно тогда, когда телефон занят сборкой шейдеров
export const WIREFRAME_INTRO = !LOW;

// 'soft' - это PCF с широким ядром: каждый затенённый фрагмент берёт
// с карты пучок выборок вместо одной. дорожает именно заливка, которой
// на телефоне и так вдвое больше от плотности. у 'percentage' край тени
// жёстче, и на экране в ладонь этого не видно
export const SHADOW_KIND: 'soft' | 'percentage' = LOW ? 'percentage' : 'soft';

// площадной источник в three считается интегралом по четырёхугольнику
// с двумя выборками из таблиц - на порядок дороже направленного, и платит
// за это каждый фрагмент. второй стоит на 0.14 и держит нижнюю кромку
// корпуса: на телефоне за него отдают полный проход заливки
export const FILL_LIGHTS = LOW ? 1 : 2;

// через сколько кадров движения перерисовывается карта теней. на кадрах,
// где едет одна камера, она не перерисовывается вовсе (Stage.tsx). тень
// мягкая, отставания на кадр глазом не поймать, а проход стоит двухсот
// тысяч треугольников - три четверти основного
export const SHADOW_EVERY = LOW ? 2 : 1;
